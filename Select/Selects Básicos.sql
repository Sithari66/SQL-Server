-- RECUPERAR DADOS DE TODA TABELA
SELECT
	*
FROM
	TABELA


-- RECUPERAR DADOS ESPECÍFICOS DE UMA TABELA
SELECT
	*
FROM
	TABELA
WHERE
	DADO = 1234


-- RECUPERAR DADOS ENTRE UM INTERVALO DE VALORES
SELECT
	*
FROM
	TABELA
WHERE
	DADO BETWEEN 1000 AND 2000


-- RECUPERAR DADOS DE UMA DATA ESPECÍFICA
SELECT
	*
FROM
	TABELA
WHERE
	DAY(DATA) = 11 AND 
	MONTH(DATA) = 10 AND 
	YEAR(DATA) = 2026


-- RECUPERAR DADOS DE UMA DATA ESPECÍFICA (FORMA MAIS PERFORMÁTICA)
SELECT
	*
FROM
	TABELA
WHERE
	CAST(DATA AS DATE) = '2026-10-11'


-- RECUPERAR DADOS POR UMA DESCRIÇÃO ESPECÍFICA
SELECT 
	* 
FROM 
	TABELA 
WHERE
	 DESCRICAO LIKE '%CONSULTA%' 