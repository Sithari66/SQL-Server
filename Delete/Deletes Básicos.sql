-- DELETE BÁSICO
DELETE FROM TABELA AS TAB
WHERE 
	TAB.ID = 1


-- DELETE COM INNER JOIN
-- PERFORMANCE PIOR QUE O DELETE COM SUBQUERY
DELETE TAB FROM TABELA AS TAB

	INNER JOIN TABELA2 AS TAB2 WITH(NOLOCK) ON 
		TAB.ID = TAB2.ID

WHERE 
	TAB2.STATUS = 'EXPIRADO';


-- DELETE COM SUBQUERY
-- PERFORMANCE MELHOR QUE O INNER JOIN
DELETE FROM TABELA
WHERE 
	ID NOT IN (
				SELECT DISTINCT 
					TABELA_ID 
				FROM 
					TABELA_RELACIONAMENTO
);
