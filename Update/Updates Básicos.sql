UPDATE TAB SET
	TAB.NOME = (
				 SELECT 
					TAB2.NOME_NOVO 
				 FROM 
					TABELA2 AS TAB2 
				 WHERE 
					TAB2.ID = TAB.ID
)
WHERE 
	EXISTS (
			SELECT 1 
			FROM 
				TABELA2 AS TAB2 
			WHERE 
				TAB2.ID = TAB.ID AND 
				TAB.ID = 1
);



